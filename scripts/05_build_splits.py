"""Build every split regime and audit it for leakage.

Stage 4 of the pipeline. Produces, for each regime and seed, the train/val/test
assignment of dataset rows, plus the two thesis tables that go with them: the
split profile and the leakage audit.

The expensive pieces are cached because they do not depend on the seed or the
regime, and recomputing them would dominate every re-run:

    fingerprints.npy        ECFP4 for 190,339 compounds
    compound_clusters.npy   Butina sphere exclusion over those fingerprints
    target_identity.npz     exact pairwise domain identity for 565 targets
    target_clusters.npy     single-linkage target groups

Outputs:
    data/splits/{regime}_seed{n}.parquet
    reports/tables/06_splits.md
    reports/tables/07_leakage_audit.md

Usage::

    python scripts/05_build_splits.py
    python scripts/05_build_splits.py --force-clusters   # redo the N^2 pass
    python scripts/05_build_splits.py --seeds 0          # one seed, for a trial
"""

from __future__ import annotations

import argparse
import sys
import time
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from dti.clustering import identity_clusters, sphere_exclusion  # noqa: E402
from dti.config import REPO_ROOT, load_config  # noqa: E402
from dti.leakage import audit_split, family_composition  # noqa: E402
from dti.molecules import fingerprint_matrix, make_fingerprint_generator  # noqa: E402
from dti.sequences import load_or_compute  # noqa: E402
from dti.similarity import max_similarity, pick_device  # noqa: E402
from dti.splits import filter_r4b, split_grouped, split_r1, split_r4a  # noqa: E402


def build_indices(data: pd.DataFrame) -> tuple[np.ndarray, np.ndarray, list, list]:
    """Map every row to a compound index and a target index.

    Compounds are keyed on canonical SMILES, which is the decision made in
    stage 3: two ChEMBL records of one molecule are one compound, so they get
    one index and cannot land on both sides of a split.
    """
    compounds = sorted(data["canonical_smiles"].unique())
    targets = sorted(data["tid"].unique())
    compound_pos = {s: i for i, s in enumerate(compounds)}
    target_pos = {t: i for i, t in enumerate(targets)}
    compound_index = data["canonical_smiles"].map(compound_pos).to_numpy(np.int64)
    target_index = data["tid"].map(target_pos).to_numpy(np.int64)
    return compound_index, target_index, compounds, targets


def load_fingerprints(
    compounds: list[str], cache: Path, config, force: bool
) -> np.ndarray:
    n_bits = config["splits"]["r2_compound"]["n_bits"]
    radius = config["splits"]["r2_compound"]["radius"]
    if cache.exists() and not force:
        fps = np.load(cache)
        if fps.shape == (len(compounds), n_bits):
            print(f"  fingerprints: cached {fps.shape}")
            return fps
        print("  cached fingerprints do not match the dataset; recomputing")

    print(f"  fingerprints: {len(compounds):,} compounds, ECFP{2 * radius}")
    started = time.perf_counter()
    generator = make_fingerprint_generator(radius=radius, n_bits=n_bits)
    fps = fingerprint_matrix(compounds, generator)
    print(f"    {time.perf_counter() - started:.0f}s")
    np.save(cache, fps)
    return fps


def load_compound_clusters(
    fps: np.ndarray, cache: Path, cutoff: float, force: bool, device
) -> np.ndarray:
    if cache.exists() and not force:
        labels = np.load(cache)
        if len(labels) == len(fps):
            print(f"  compound clusters: cached {len(np.unique(labels)):,}")
            return labels
        print("  cached clusters do not match the fingerprints; recomputing")

    print(f"  compound clusters: sphere exclusion at Tanimoto {cutoff} on {device}")
    started = time.perf_counter()
    labels = sphere_exclusion(fps, cutoff, device=device, progress=True)
    print(
        f"    {len(np.unique(labels)):,} clusters in "
        f"{(time.perf_counter() - started) / 60:.1f} min"
    )
    np.save(cache, labels)
    return labels


def cluster_profile(labels: np.ndarray, name: str) -> list[str]:
    _, counts = np.unique(labels, return_counts=True)
    counts = np.sort(counts)[::-1]
    return [
        f"- {name}: **{len(counts):,}** gruplar / groups, "
        f"en büyük / largest **{counts[0]:,}**, "
        f"ortanca / median **{int(np.median(counts))}**, "
        f"tekil / singletons **{int((counts == 1).sum()):,}** "
        f"(%{100 * (counts == 1).sum() / len(counts):.1f})",
    ]


def write_split_profile(
    records: pd.DataFrame, cluster_lines: list[str], config, notes: list[str]
) -> Path:
    lines = [
        "# Split profile / Bölme profili",
        "",
        "Generated by `scripts/05_build_splits.py`.",
        "",
        "Gruplar bölünür, satırlar değil; bu yüzden hedeflenen oranlar yaklaşık",
        "tutulur ve gerçekleşen oran burada rapor edilir.",
        "",
        "Whole groups are assigned, not rows, so the configured fractions are",
        "approximate and the achieved fraction is what is reported.",
        "",
        "## Grouping / Gruplama",
        "",
        *cluster_lines,
        "",
        "## Splits / Bölmeler",
        "",
        "| Rejim / Regime | Tohum / Seed | Eğitim / Train | Doğrulama / Val "
        "| Test | Test oranı | Test bileşiği | Test hedefi |",
        "| --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for row in records.itertuples():
        lines.append(
            f"| {row.regime} | {row.seed} | {row.n_train:,} | {row.n_val:,} "
            f"| {row.n_test:,} | %{100 * row.test_fraction:.1f} "
            f"| {row.n_test_compounds:,} | {row.n_test_targets:,} |"
        )
    if notes:
        lines += ["", "## Notes / Notlar", ""] + notes
    out = config.path("tables") / "06_splits.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return out


def write_leakage_audit(records: pd.DataFrame, config) -> Path:
    tanimoto_cutoff = config["splits"]["r2_compound"]["tanimoto_cutoff"]
    identity_cutoff = config["splits"]["r3_target"]["sequence_identity"]
    # Averaged over seeds: the per-seed numbers are in the parquet, but the
    # table a reader needs is one row per regime.
    grouped = (
        records.groupby("regime", as_index=False)
        .agg(
            {
                "identical_molecules": "max",
                "tanimoto_p50": "mean",
                "tanimoto_p95": "mean",
                "tanimoto_max": "max",
                "share_compounds_above_tanimoto_cutoff": "mean",
                "shared_targets": "max",
                "identity_p50": "mean",
                "identity_max": "max",
                "share_targets_above_identity_cutoff": "mean",
            }
        )
        .sort_values("regime")
    )

    lines = [
        "# Leakage audit / Kaçak denetimi",
        "",
        "Generated by `scripts/05_build_splits.py`.",
        "",
        "Hiçbir rejimin skoru bu sayılar olmadan yorumlanamaz. Bir bölme kendi",
        "tanımını sağlayıp hâlâ kolay olabilir: Butina kümelemesi kümeler",
        "*arası* benzerliğe sınır koymaz, bu yüzden R2'de bir test molekülü",
        "hâlâ bir eğitim molekülünün yakın analoğu olabilir. Burada ölçülen de",
        "tam olarak bu.",
        "",
        "No regime's score is interpretable without these. A split can satisfy",
        "its own definition and still be easy, so cross-side similarity is",
        "measured rather than assumed from the construction.",
        "",
        f"Eşikler / cutoffs: Tanimoto {tanimoto_cutoff}, "
        f"dizi kimliği / sequence identity {identity_cutoff}.",
        "",
        "| Rejim / Regime | Aynı molekül | Tanimoto ortanca | Tanimoto p95 "
        "| Tanimoto maks | Eşik üstü bileşik | Dizi kimliği ortanca "
        "| Dizi kimliği maks | Eşik üstü hedef |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for row in grouped.itertuples():
        lines.append(
            f"| {row.regime} | {row.identical_molecules:,} "
            f"| {row.tanimoto_p50:.3f} | {row.tanimoto_p95:.3f} "
            f"| {row.tanimoto_max:.3f} "
            f"| %{100 * row.share_compounds_above_tanimoto_cutoff:.1f} "
            f"| {row.identity_p50:.3f} | {row.identity_max:.3f} "
            f"| %{100 * row.share_targets_above_identity_cutoff:.1f} |"
        )
    lines += [
        "",
        "**Nasıl okunur / How to read this.**",
        "",
        "`Aynı molekül` yalnızca **R2 ve R4b**'de sıfır olmalı; bu ikisi onu",
        "engellemek için kurulmuştur, sıfır değilse bu bir bulgu değil hatadır.",
        "Diğer rejimlerde sıfır olmaması **doğrudur**: R1 iyimser taban",
        "çizgisidir; R3 *hedefleri* dışarıda bırakır, dolayısıyla aynı bileşiğin",
        "farklı proteinlere karşı iki yakada görünmesi beklenen davranıştır; R4a",
        "bir *aileyi* dışarıda bırakır, dolayısıyla hem kinaza hem GPCR'a karşı",
        "ölçülmüş promiskü bir bileşik meşru biçimde iki yakada yer alır — R4b'nin",
        "var olma sebebi tam olarak budur.",
        "",
        "`Tanimoto maks` tek bir şanssız çiftten gelebilir; rejimin iddia ettiği",
        "şeyi ölçüp ölçmediğini söyleyen sayı `Eşik üstü bileşik` oranıdır.",
        "",
        "`Dizi kimliği` yerel hizalama kimliği değil, **kısa dizi üzerinden**",
        "kimliktir (aynı kalıntı sayısı / kısa alanın uzunluğu). Bu ayrım",
        "önemli: denetimin ilk sürümü yerel hizalama kimliğini raporluyor ve",
        "her rejim için 1,000 veriyordu — hiçbir hedefin iki yakada bulunmadığı",
        "R3 dahil. Sebep bölmede değil metrikteydi: iki alakasız proteinin",
        "%3'ünü kaplayan %70 kimlikli bir hizalama, protein benzerliği değil",
        "motif eşleşmesidir.",
        "",
        "`identical molecules` must be zero in **R2 and R4b only**. A non-zero",
        "value elsewhere is correct, not a defect: R1 is the optimistic",
        "baseline, R3 holds out targets so one compound may appear on both",
        "sides measured against different proteins, and R4a holds out a family",
        "so a promiscuous compound legitimately appears on both sides.",
        "Identity is reported over the shorter domain, not over the local",
        "alignment, because the latter reports a 3% motif match as full",
        "identity.",
    ]
    out = config.path("tables") / "07_leakage_audit.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return out


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--force-fingerprints", action="store_true")
    parser.add_argument("--force-clusters", action="store_true")
    parser.add_argument("--force-identity", action="store_true")
    parser.add_argument(
        "--seeds", type=int, nargs="*", help="override the configured seeds"
    )
    parser.add_argument("--cpu", action="store_true", help="disable the GPU path")
    args = parser.parse_args()

    config = load_config()
    interim = config.path("interim")
    splits_dir = config.path("splits")
    splits_dir.mkdir(parents=True, exist_ok=True)
    device = pick_device(prefer_gpu=not args.cpu)

    dataset_path = config.path("processed") / "dataset.parquet"
    if not dataset_path.exists():
        raise SystemExit(f"{dataset_path} missing. Run scripts/04_build_dataset.py.")

    print("Loading")
    data = pd.read_parquet(dataset_path)
    compound_index, target_index, compounds, targets = build_indices(data)
    families = data["family"].to_numpy()
    print(
        f"  {len(data):,} rows  {len(compounds):,} compounds  "
        f"{len(targets):,} targets  device={device}"
    )

    print("\nGrouping")
    fps = load_fingerprints(
        compounds, interim / "fingerprints.npy", config, args.force_fingerprints
    )
    r2_cutoff = config["splits"]["r2_compound"]["tanimoto_cutoff"]
    compound_clusters = load_compound_clusters(
        fps, interim / "compound_clusters.npy", r2_cutoff, args.force_clusters, device
    )

    target_frame = (
        data.drop_duplicates("tid").set_index("tid").loc[targets]
    )
    identity, coverage, identity_over_shorter = load_or_compute(
        interim / "target_identity.npz",
        [str(t) for t in targets],
        target_frame["domain_sequence"].tolist(),
        force=args.force_identity,
    )
    r3 = config["splits"]["r3_target"]
    # Clustered on the same metric the audit reports, so R3's guarantee holds
    # by construction instead of up to a definitional gap. The earlier
    # identity+coverage grouping is printed alongside as the ablation it now is.
    target_clusters = identity_clusters(
        identity_over_shorter,
        np.ones_like(identity_over_shorter),
        r3["sequence_identity"],
        0.0,
    )
    np.save(interim / "target_clusters.npy", target_clusters)
    print(
        f"  target groups: {len(np.unique(target_clusters)):,} at "
        f"identity-over-shorter >= {r3['sequence_identity']}"
    )
    ablation = identity_clusters(
        identity, coverage, r3["sequence_identity"], r3["coverage"]
    )
    print(
        f"  (ablation: local-alignment identity >= {r3['sequence_identity']} "
        f"with coverage >= {r3['coverage']} would give "
        f"{len(np.unique(ablation)):,} groups)"
    )

    cluster_lines = (
        cluster_profile(compound_clusters, f"Bileşik kümeleri / compound clusters (Butina, {r2_cutoff})")
        + cluster_profile(
            target_clusters,
            f"Hedef grupları / target groups (tek bağlantı / single linkage, {r3['sequence_identity']})",
        )
    )

    seeds = args.seeds if args.seeds else config.seeds
    test_fraction = config["splits"]["test_fraction"]
    val_fraction = config["splits"]["val_fraction"]
    r4 = config["splits"]["r4_family"]
    identity_cutoff = r3["sequence_identity"]

    print(f"\nBuilding splits for seeds {list(seeds)}")
    audits: list[dict] = []
    compositions: list[pd.DataFrame] = []
    notes: list[str] = []

    # Per-row group labels for the grouped regimes.
    compound_group_of_row = compound_clusters[compound_index]
    target_group_of_row = target_clusters[target_index]

    for seed in seeds:
        built = [
            split_r1(len(data), seed, test_fraction, val_fraction),
            split_grouped(
                "R2", compound_group_of_row, seed, test_fraction, val_fraction,
                unit="compound_cluster",
            ),
            split_grouped(
                "R3", target_group_of_row, seed, test_fraction, val_fraction,
                unit="target_group",
            ),
        ]
        for split in built:
            audits.append(
                audit_split(
                    split, compound_index, target_index, fps, identity_over_shorter,
                    tanimoto_cutoff=r2_cutoff, identity_cutoff=identity_cutoff,
                    device=device,
                )
            )

        for family in config.active_families:
            r4a = split_r4a(families, family, seed, val_fraction)
            # One N^2 pass serves three consumers: the R4b filter, the R4a
            # audit and the R4b audit. The training set is the same for all
            # three, so the similarity is a property of the molecule alone.
            test_compounds = np.unique(compound_index[r4a.test])
            train_compounds = np.unique(compound_index[r4a.train])
            best, _ = max_similarity(
                fps[test_compounds], fps[train_compounds], device=device
            )
            per_compound = np.zeros(len(compounds), dtype=np.float32)
            per_compound[test_compounds] = best

            r4b = filter_r4b(
                r4a,
                compound_index,
                per_compound,
                r4["r4b_tanimoto_cutoff"],
                r4["r4b_min_test_records"],
            )
            if not r4b.meta["scorable"]:
                notes.append(
                    f"- **{r4b.regime}** (seed {seed}): "
                    f"{len(r4b.test):,} kayıt kaldı, eşik "
                    f"{r4['r4b_min_test_records']} — bu aile R4b'de "
                    f"**puanlanmayacak**, yalnız kalan sayı rapor edilir."
                )
            for split in (r4a, r4b):
                audits.append(
                    audit_split(
                        split, compound_index, target_index, fps, identity_over_shorter,
                        tanimoto_cutoff=r2_cutoff,
                        identity_cutoff=identity_cutoff,
                        device=device,
                        compound_max_similarity=per_compound,
                    )
                )
                built.append(split)

        for split in built:
            frame = pd.DataFrame(
                {
                    "row": np.concatenate([split.train, split.val, split.test]),
                    "fold": (
                        ["train"] * len(split.train)
                        + ["val"] * len(split.val)
                        + ["test"] * len(split.test)
                    ),
                }
            )
            frame.to_parquet(
                splits_dir / f"{split.regime}_seed{seed}.parquet", index=False
            )
            composition = family_composition(split, families)
            composition["regime"] = split.regime
            composition["seed"] = seed
            compositions.append(composition)
        print(f"  seed {seed}: {len(built)} splits written")

    audit_frame = pd.DataFrame(audits)
    audit_frame.to_parquet(interim / "leakage_audit.parquet", index=False)
    pd.concat(compositions).to_parquet(
        interim / "split_family_composition.parquet", index=False
    )

    profile_path = write_split_profile(
        audit_frame[audit_frame["seed"] == seeds[0]], cluster_lines, config, notes
    )
    audit_path = write_leakage_audit(audit_frame, config)

    print(f"\nSplits:  {splits_dir.relative_to(REPO_ROOT)}")
    print(f"Profile: {profile_path.relative_to(REPO_ROOT)}")
    print(f"Audit:   {audit_path.relative_to(REPO_ROOT)}")

    worst = audit_frame.loc[audit_frame["tanimoto_max"].idxmax()]
    print(
        f"\n  highest train-test Tanimoto: {worst['tanimoto_max']:.3f} "
        f"in {worst['regime']} (seed {worst['seed']})"
    )
    leaked = audit_frame[audit_frame["identical_molecules"] > 0]["regime"].unique()
    print(f"  regimes sharing identical molecules: {list(leaked) or 'none'}")
    print("\nNext: python scripts/06_extract_embeddings.py")
    return 0


if __name__ == "__main__":
    sys.exit(main())
